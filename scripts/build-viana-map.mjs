import fs from 'node:fs';

// Public IBGE meshes. Equirectangular projection, sufficient for this location graphic.
const project = ([lon, lat]) => [(lon + 75) * 25, (5 - lat) * 25];
function ringPath(ring, tolerance) {
  const points = ring.filter((point, i) => i === 0 || i === ring.length - 1 || Math.hypot(point[0] - ring[i - 1][0], point[1] - ring[i - 1][1]) > tolerance);
  return points.map((point, i) => `${i ? 'L' : 'M'}${project(point).map(n => n.toFixed(2)).join(',')}`).join('') + 'Z';
}
function paths(file, tolerance) {
  return JSON.parse(fs.readFileSync(file, 'utf8')).features.map(feature => {
    const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
    return { id: feature.properties.codarea, path: polygons.map(polygon => polygon.map(ring => ringPath(ring, tolerance)).join('')).join('') };
  });
}
const states = paths('public/maps/brasil-estados.geojson', 0.015);
const municipalities = paths('public/maps/espirito-santo.geojson', 0.002);
const source = JSON.parse(fs.readFileSync('public/maps/espirito-santo.geojson', 'utf8')).features.find(f => f.properties.codarea === '3205101');
const coordinates = source.geometry.coordinates.flat(source.geometry.type === 'Polygon' ? 1 : 2);
const xs = coordinates.map(p => p[0]), ys = coordinates.map(p => p[1]);
const pin = project([(Math.min(...xs) + Math.max(...xs)) / 2, (Math.min(...ys) + Math.max(...ys)) / 2]);
fs.writeFileSync('src/data/viana-map.ts', `// Generated by scripts/build-viana-map.mjs from IBGE public meshes.\n// Pin marks the municipality's geographic bounding-box center, not an event venue.\nexport const mapStates = ${JSON.stringify(states)};\nexport const mapMunicipalities = ${JSON.stringify(municipalities)};\nexport const vianaPin = ${JSON.stringify(pin.map(n => +n.toFixed(2)))};\n`);
console.log({ states: states.length, municipalities: municipalities.length, pin, bytes: fs.statSync('src/data/viana-map.ts').size });
